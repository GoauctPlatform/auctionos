def get_state_aliases(search_term: str):
    search_term = search_term.strip().upper()
    aliases = [search_term]
    
    # Check if it's an abbreviation
    if search_term in US_STATES:
        aliases.append(US_STATES[search_term].upper())
        
    # Check if it's a full name
    for abbr, full_name in US_STATES.items():
        if full_name.upper() == search_term:
            aliases.append(abbr)
            break
            
    return aliases
